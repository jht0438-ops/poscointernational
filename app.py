# 수익성: 절대 이익규모와 이익률을 4개 후보 내 순위로 평가.
# 1위 15점, 2위 12점, 3위 9점, 4위 6점으로 고정해 규모가 큰 한 사업이 점수를 과도하게 독식하지 않도록 함.
rank_points = {1: 15, 2: 12, 3: 9, 4: 6}
candidates["이익규모점수"] = candidates["2026Q2 영업이익"].rank(ascending=False, method="min").astype(int).map(rank_points)
candidates["이익률점수"] = candidates["2026Q2 영업이익률"].rank(ascending=False, method="min").astype(int).map(rank_points)
candidates["수익성점수"] = candidates["이익규모점수"] + candidates["이익률점수"]

# 지속가능성 25점 = 최근 이익추세 10 + 이익 원인의 질 15
# 최근 이익추세: 최신 YoY 영업이익 성장률 구간 점수

def trend_score(x):
    if x >= 50: return 10
    if x >= 20: return 8
    if x >= 0: return 6
    if x >= -20: return 4
    return 2

candidates["이익추세점수"] = candidates["YoY 영업이익증감률"].apply(trend_score)
candidates["원인의질점수"] = candidates["구조적원인등급"] * 3
candidates["지속가능성점수"] = candidates["이익추세점수"] + candidates["원인의질점수"]

